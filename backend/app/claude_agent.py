def _load_knowledge_base_text(channel: Channel, free_text: str) -> str:
    db = get_db()
    docs = db.collection(knowledge_base_collection(channel)).stream()
    pairs = []
    for doc in docs:
        data = doc.to_dict()
        question = data.get("question", "").strip()
        answer = data.get("answer", "").strip()
        if question and answer:
            pairs.append(f"В: {question}\nО: {answer}")

    sections = []
    if pairs:
        sections.append(
            "# ДОПОЛНИТЕЛЬНАЯ БАЗА ЗНАНИЙ (вопрос-ответ, редактируется админом)\n"
            + "\n\n".join(pairs)
        )
    if free_text and free_text.strip():
        sections.append("# ДОПОЛНИТЕЛЬНАЯ БАЗА ЗНАНИЙ (свободный текст, редактируется админом)\n" + free_text.strip())

    if not sections:
        return ""
    return "\n\n" + "\n\n".join(sections)


def _build_system_prompt(channel: Channel) -> str:
    profile = get_agent_settings(channel)
    today = dt.date.today().isoformat()

    header = (
        f"Сегодняшняя дата: {today}.\n\n"
        f"Ты — {profile['name']}, представитель компании «{profile['company']}».\n"
        f"Товары/услуги: {profile['products']}\n\n"
        f"{profile['goal']}\n\n"
    )
    return header + STATIC_FACTS + _load_knowledge_base_text(channel, profile.get("knowledgeBaseText", ""))


